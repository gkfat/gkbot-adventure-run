export const resolveDialogueLines = (subject: DialogueSubject, trigger: DialogueTrigger): string[] => {
    if (subject.kind === 'player') {
        const specific = PLAYER_DIALOGUE_LINES[subject.archetypeId]?.[trigger];
        if (specific?.length) return specific;
        return GENERIC_PLAYER_LINES[trigger] ?? [];
    }

    const specific = subject.archetypeSlug ? ENEMY_DIALOGUE_LINES[subject.archetypeSlug]?.[trigger] : undefined;
    if (specific?.length) return specific;
    return GENERIC_ENEMY_LINES_BY_FACTION[subject.faction][trigger] ?? [];
};
